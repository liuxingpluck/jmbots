/**
 * 装/卸开机自动启动：在 Windows 的"启动"文件夹里放一个 .vbs，登录时无窗口地把看门狗起起来。
 *
 * 为什么用启动文件夹而不是计划任务：用户 10-31 明确不想用 Windows 计划任务管这类生命周期，
 * 10-28 也反馈过定时任务反复闪命令窗口"很烦"。启动文件夹里的 .vbs 用 `Run(..., 0, False)`
 * 起进程，窗口是真的没有（不是最小化）。
 *
 * 装上之后开机就有看门狗，看门狗会把服务起起来、挂了再拉起来，所以服务能一直自己管自己。
 *
 * 用法（在 Windows 上跑）：
 *   bun scripts/Install_Autostart.ts            装上（已有就覆盖）
 *   bun scripts/Install_Autostart.ts --remove   卸掉
 *   bun scripts/Install_Autostart.ts --show     只看现在装的是什么
 * 可带 --port、--host、--runtime，会写进 .vbs 里。
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import * as serveProcess from './Serve_Process.ts';


/** 放进启动文件夹的文件名。 */
const VBS_NAME = 'jmbots_Guard.vbs';


/**
 * 启动文件夹的位置（当前用户的，不是所有用户的——不用管理员权限）。
 * @returns 完整路径。
 * @throws 拿不到 APPDATA 时抛出（不在 Windows 上跑就会这样）。
 */
function startupDir(): string {
  /** 漫游配置目录。 */
  const appData = process.env.APPDATA;
  if (!appData) {
    throw new Error('拿不到 APPDATA，这个脚本要在 Windows 上跑（虚拟机里的 Claude 请交给 DSH 执行）。');
  }
  return path.join(appData, 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup');
}


/**
 * 生成 .vbs 的内容：切到代码目录，隐藏地跑 bun scripts/Guard.ts，输出追加进运行时日志。
 * @param runtimeDir 运行时目录。
 * @param port 端口。
 * @param host 监听地址。
 * @returns .vbs 全文（只用 ASCII，避免脚本宿主按别的编码读）。
 */
function buildVbs(runtimeDir: string, port: string, host: string): string {
  /** 看门狗起不来时的输出去哪（正常情况下看门狗自己写 guard_<日期>.log）。 */
  const logFile = path.join(runtimeDir, 'data', 'guard_autostart.log');
  /**
   * 包一层引号给 cmd 用。VBScript 字符串里的一个双引号要写成两个，所以这里是四个。
   * @param text 要包起来的路径。
   */
  const quote = (text: string): string => `""${text}""`;
  /** 要跑的命令行（cmd /c 负责把输出重定向到日志）。 */
  const command = `cmd /c bun.cmd scripts\\Guard.ts --port ${port} --host ${host} --runtime ${quote(runtimeDir)} >> ${quote(logFile)} 2>&1`;
  return [
    "' jmbots watchdog - starts hidden at logon. Generated by scripts/Install_Autostart.ts.",
    "' Delete this file (or run: bun scripts/Install_Autostart.ts --remove) to turn it off.",
    'Set shell = CreateObject("WScript.Shell")',
    `shell.CurrentDirectory = "${serveProcess.ROOT.replace(/\//g, '\\')}"`,
    `shell.Run "${command}", 0, False`,
    '',
  ].join('\r\n');
}


/**
 * 入口。
 */
function main(): void {
  /** 启动文件夹里那个文件。 */
  const target = path.join(startupDir(), VBS_NAME);

  if (process.argv.includes('--show')) {
    console.log(fs.existsSync(target) ? `已装：${target}\n\n${fs.readFileSync(target, 'utf8')}` : `没装（${target} 不存在）`);
    return;
  }

  if (process.argv.includes('--remove')) {
    if (!fs.existsSync(target)) {
      console.log(`本来就没装（${target} 不存在）。`);
      return;
    }
    fs.rmSync(target);
    console.log(`已卸掉：${target}\n（已经在跑的看门狗不受影响，要停它就在任务管理器里结束那个 bun 进程。）`);
    return;
  }

  /** 运行时目录。 */
  const runtimeDir = serveProcess.runtimeDir().replace(/\//g, '\\');
  //G .vbs 按 ASCII 写，路径里有中文或别的非 ASCII 字符时 WScript 可能读错，先说清楚。
  if (/[^\x20-\x7e\\]/.test(`${serveProcess.ROOT}${runtimeDir}`)) {
    console.log(`注意：代码目录或运行时目录里有非 ASCII 字符，.vbs 可能读不对路径。\n  代码：${serveProcess.ROOT}\n  运行时：${runtimeDir}`);
  }
  fs.writeFileSync(target, buildVbs(runtimeDir, serveProcess.option('port', '30086'), serveProcess.option('host', '0.0.0.0')));
  console.log(`装好了：${target}\n下次登录 Windows 就会无窗口地起看门狗，它会把服务起起来、挂了再拉起来。\n现在就想起的话，双击 scripts\\Start_Serve.cmd。\n卸掉：bun scripts/Install_Autostart.ts --remove`);
}


main();
